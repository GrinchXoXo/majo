package storage

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// ErrNotFound is returned by Get when no object exists at the key.
var ErrNotFound = errors.New("storage: object not found")

// ErrURLNotSupported is returned by LocalProvider.GenerateURL: Phase 4A.1
// stores media, it does not distribute it, so there are no public URLs.
var ErrURLNotSupported = errors.New("storage: URL generation not supported by the local provider")

// InvalidKeyError rejects keys that could escape the storage root. It is
// permanent: retrying with the same key fails the same way.
type InvalidKeyError struct{ Key string }

func (e InvalidKeyError) Error() string   { return fmt.Sprintf("storage: invalid key %q", e.Key) }
func (e InvalidKeyError) Permanent() bool { return true }

// keyPattern: relative, slash-separated segments of [A-Za-z0-9._-], no
// empty, "." or ".." segments. Keys are generated by Majo (never taken
// from inbound data), and this is the second line of defence.
var keyPattern = regexp.MustCompile(`^[A-Za-z0-9_-][A-Za-z0-9._-]*(/[A-Za-z0-9_-][A-Za-z0-9._-]*)*$`)

// LocalProvider is the Phase 4A.1 storage.Provider: files under a
// configurable root directory on the server's disk (decision O-2 allows
// local disk for a single-server pilot). Filesystem paths never leave this
// type: callers only see keys.
type LocalProvider struct {
	root string
}

// NewLocalProvider creates the root directory (0700) if needed.
func NewLocalProvider(root string) (*LocalProvider, error) {
	if strings.TrimSpace(root) == "" {
		return nil, errors.New("storage: local root directory is required")
	}
	abs, err := filepath.Abs(root)
	if err != nil {
		return nil, fmt.Errorf("storage: resolving root: %w", err)
	}
	if err := os.MkdirAll(abs, 0o700); err != nil {
		return nil, fmt.Errorf("storage: creating root: %w", err)
	}
	return &LocalProvider{root: abs}, nil
}

func (p *LocalProvider) path(key string) (string, error) {
	if !keyPattern.MatchString(key) || strings.Contains(key, "..") {
		return "", InvalidKeyError{key}
	}
	full := filepath.Join(p.root, filepath.FromSlash(key))
	if !strings.HasPrefix(full, p.root+string(os.PathSeparator)) {
		return "", InvalidKeyError{key}
	}
	return full, nil
}

// Put writes atomically: a temp file in the same directory, fsync, then
// rename over the target. Writing the same key again replaces the object,
// which is what makes retries with a deterministic key idempotent.
// contentType is not persisted (the MediaAsset row records it).
func (p *LocalProvider) Put(ctx context.Context, key string, data []byte, contentType string) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	full, err := p.path(key)
	if err != nil {
		return err
	}
	dir := filepath.Dir(full)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return fmt.Errorf("storage: creating directory: %w", err)
	}
	tmp, err := os.CreateTemp(dir, ".tmp-*")
	if err != nil {
		return fmt.Errorf("storage: creating temp file: %w", err)
	}
	tmpName := tmp.Name()
	cleanup := func() { _ = os.Remove(tmpName) }
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		cleanup()
		return fmt.Errorf("storage: writing: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		cleanup()
		return fmt.Errorf("storage: syncing: %w", err)
	}
	if err := tmp.Close(); err != nil {
		cleanup()
		return fmt.Errorf("storage: closing: %w", err)
	}
	if err := os.Chmod(tmpName, 0o600); err != nil {
		cleanup()
		return fmt.Errorf("storage: chmod: %w", err)
	}
	if err := os.Rename(tmpName, full); err != nil {
		cleanup()
		return fmt.Errorf("storage: committing: %w", err)
	}
	// Persist the rename itself (directory entry) where supported.
	if d, err := os.Open(dir); err == nil {
		_ = d.Sync()
		d.Close()
	}
	return nil
}

func (p *LocalProvider) Get(ctx context.Context, key string) ([]byte, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	full, err := p.path(key)
	if err != nil {
		return nil, err
	}
	b, err := os.ReadFile(full)
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrNotFound
	}
	return b, err
}

// Delete removes the object. Deleting a missing key is not an error.
func (p *LocalProvider) Delete(ctx context.Context, key string) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	full, err := p.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(full); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

// GenerateURL is deliberately unsupported: no public or filesystem URLs.
func (p *LocalProvider) GenerateURL(ctx context.Context, key string) (string, error) {
	return "", ErrURLNotSupported
}
