-- Phase 4A.1: durable media ingestion foundation.
-- Additive only. Two new tables and one nullable link column:
--   jobs          minimal Postgres-backed durable job queue (in-process worker,
--                 FOR UPDATE SKIP LOCKED). No broker. Architecture Lock V2 §C-14.
--   media_assets  Majo's durable, vendor-owned copy of inbound media. WhatsApp
--                 is only the transport; the asset is the thing referenced
--                 everywhere later (Lock V2 §I, invariant 10).
--   messages.media_asset_id  which asset an inbound media message resolved to
--                 (also set when the bytes deduplicated onto an existing asset).

-- ---------------------------------------------------------------------------
-- jobs
-- ---------------------------------------------------------------------------
-- Lifecycle: PENDING -> RUNNING -> SUCCEEDED
--                       RUNNING -> PENDING (retry, run_at in the future)
--                       RUNNING -> FAILED  (permanent error or attempts exhausted)
-- A RUNNING job whose lease (locked_at) is older than the worker's lease
-- duration is reclaimable: that is how a job survives a worker killed mid-run.
-- Execution is at-least-once; handlers make their effects idempotent.
CREATE TABLE jobs (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    job_type         TEXT NOT NULL,                 -- e.g. MEDIA_DOWNLOAD
    -- Caller-chosen identity of the unit of work (e.g. the source message
    -- ID). Re-enqueueing the same work is a no-op.
    idempotency_key  TEXT NOT NULL,
    payload          JSONB NOT NULL DEFAULT '{}'::jsonb,
    status           TEXT NOT NULL DEFAULT 'PENDING'
                     CHECK (status IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    attempts         INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),   -- incremented on every claim
    max_attempts     INTEGER NOT NULL CHECK (max_attempts > 0),
    run_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_at        TIMESTAMPTZ,
    locked_by        TEXT,
    last_error       TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at     TIMESTAMPTZ,                   -- set on SUCCEEDED or FAILED

    UNIQUE (job_type, idempotency_key)
);

-- Claim scan: due PENDING jobs and stale RUNNING jobs, oldest run_at first.
CREATE INDEX idx_jobs_claimable ON jobs (job_type, run_at)
    WHERE status IN ('PENDING', 'RUNNING');
-- Operator view of terminal failures.
CREATE INDEX idx_jobs_failed ON jobs (job_type, updated_at) WHERE status = 'FAILED';

-- ---------------------------------------------------------------------------
-- media_assets
-- ---------------------------------------------------------------------------
-- A row exists only after the bytes were written to storage.Provider, so a
-- row means "Majo can retrieve this". status is deliberately tiny:
-- AVAILABLE is the only state any code path writes in 4A.1; REMOVED is
-- reserved for future moderation/deletion and is not implemented.
-- Stored != published: nothing here implies vendor consent to redistribute.
CREATE TABLE media_assets (
    id                         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_vendor_id            UUID NOT NULL REFERENCES vendors(id),
    kind                       TEXT NOT NULL CHECK (kind IN ('image', 'video')),
    mime_type                  TEXT NOT NULL,       -- detected from the bytes, not the header
    size_bytes                 BIGINT NOT NULL CHECK (size_bytes > 0),
    sha256                     TEXT NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    storage_key                TEXT NOT NULL UNIQUE, -- generated by Majo, never from inbound data
    -- Provenance: the FIRST inbound message that produced these bytes for
    -- this vendor. Later duplicates link via messages.media_asset_id.
    source_message_id          UUID NOT NULL REFERENCES messages(id),
    provider                   TEXT NOT NULL,       -- e.g. whatsapp
    provider_media_id          TEXT NOT NULL,       -- transport reference, not identity
    -- Only set when the provider states an expiry. Meta's webhook and media
    -- endpoint give none, so for WhatsApp this stays NULL (no guessed value).
    provider_media_expires_at  TIMESTAMPTZ,
    status                     TEXT NOT NULL DEFAULT 'AVAILABLE'
                               CHECK (status IN ('AVAILABLE', 'REMOVED')),
    stored_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Vendor-scoped content dedupe: identical bytes from the same vendor are
    -- one logical asset; identical bytes from another vendor are a separate
    -- asset owned by that vendor.
    UNIQUE (owner_vendor_id, sha256)
);

CREATE INDEX idx_media_assets_source_message ON media_assets (source_message_id);

-- ---------------------------------------------------------------------------
-- messages -> media_assets
-- ---------------------------------------------------------------------------
ALTER TABLE messages ADD COLUMN media_asset_id UUID REFERENCES media_assets(id);
CREATE INDEX idx_messages_media_asset_id ON messages (media_asset_id) WHERE media_asset_id IS NOT NULL;
