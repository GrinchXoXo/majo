#!/usr/bin/env python3
"""Attach the REAL heuristic extractor's output to the pilot buyer samples
(ai/tests/data/buyer_samples.json and buyer_holdout.json), so the Go policy
test reads them exactly as production would. Deterministic. Usage (from the
repo root):

    python3 scripts/eval/build_pilot_corpus.py

Writes backend/internal/marketplace/testdata/pilot_corpus.json. Re-run it
whenever ai/app/extraction.py changes.
"""
import dataclasses
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "ai"))
from app.extraction import HeuristicExtractor  # noqa: E402

h = HeuristicExtractor()
out = {"about": "Pilot buyer samples + held-out set with the heuristic extractor's output. "
                "Generated by scripts/eval/build_pilot_corpus.py; do not edit by hand.",
       "cases": []}
for name in ("buyer_samples.json", "buyer_holdout.json"):
    for row in json.load(open(os.path.join(ROOT, "ai/tests/data", name), encoding="utf-8")):
        out["cases"].append({"id": row["id"], "set": name.split(".")[0], "kind": row["kind"],
                             "category": row["category"], "text": row["message"],
                             "extraction": dataclasses.asdict(h.extract(row["message"]))})
path = os.path.join(ROOT, "backend/internal/marketplace/testdata/pilot_corpus.json")
with open(path, "w", encoding="utf-8") as f:
    json.dump(out, f, indent=1, ensure_ascii=False)
    f.write("\n")
print("wrote", path, len(out["cases"]), "cases")
